"""训练、评估与部署共同遵守的小车二维几何安全契约。"""

from __future__ import annotations

import math


FOOTPRINT_HALF_LENGTH_M = 0.11
FOOTPRINT_HALF_WIDTH_M = 0.118
FOOTPRINT_RADIUS_M = math.hypot(
    FOOTPRINT_HALF_LENGTH_M, FOOTPRINT_HALF_WIDTH_M
)
PATH_SAFETY_MARGIN_M = 0.20
MAP_RESOLUTION_M = 0.05
PLANNING_CLEARANCE_M = (
    math.ceil(
        (FOOTPRINT_RADIUS_M + PATH_SAFETY_MARGIN_M) / MAP_RESOLUTION_M
    )
    * MAP_RESOLUTION_M
)

FOOTPRINT_POINTS = (
    (0.0, 0.0),
    (FOOTPRINT_HALF_LENGTH_M, FOOTPRINT_HALF_WIDTH_M),
    (FOOTPRINT_HALF_LENGTH_M, -FOOTPRINT_HALF_WIDTH_M),
    (-FOOTPRINT_HALF_LENGTH_M, -FOOTPRINT_HALF_WIDTH_M),
    (-FOOTPRINT_HALF_LENGTH_M, FOOTPRINT_HALF_WIDTH_M),
)
